"""Build a private reference review pack. No analysis logic is duplicated here."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from .normalize import load_match
from .query import query_round, select_player
from .render import render_round
from .source import Export

REFERENCE_SUBJECT = "380875cd-9d67-5e65-a6b4-c11422aae222"


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate the reference game's round reports and pending playback checklist.")
    parser.add_argument("--export", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path, help="A new directory outside the raw export")
    args = parser.parse_args()
    output = args.output_dir.resolve()
    if output == args.export.resolve() or args.export.resolve() in output.parents:
        parser.error("The verification pack must be outside the raw export.")
    if output.exists():
        parser.error("The output directory already exists; choose a new directory to preserve existing checks.")
    source = Export(args.export)
    model, _ = load_match(source)
    player = select_player(model, REFERENCE_SUBJECT)
    if len(model["rounds"]) != 22:
        parser.error("This developer review pack is specific to the reference 22-round game.")
    reports = {n: query_round(model, source, n, player) for n in (1,2,3,20)}
    cases = [
        {"id":"first_dash","round":1,"start_s":4.854,"end_s":8.442,
         "check":"Prepare at +4.854s; equip actual dash at +8.017s; fast movement +8.027s to +8.442s."},
        {"id":"second_preparation","round":1,"start_s":26.480,"end_s":27.183,
         "check":"Prepare again at +26.480s; no second corroborated dash before death at +27.183s."},
        {"id":"damage_sequence","round":1,"start_s":21.612,"end_s":27.191,
         "check":"Incoming damage 39, 55, then 6 actual; seven damaging Bandit hits; 278 actual damage dealt versus about 307.40 raw."},
        {"id":"weapon_pickup","round":1,"start_s":27.183,"end_s":28.721,
         "check":"You die at +27.183s; enemy Clove becomes owner of your Bandit at +28.721s. Later actions belong to the new owner."},
        {"id":"completed_trade","round":2,"start_s":14.010,"end_s":14.567,
         "check":"Enemy Jett kills teammate Raze; teammate Cypher kills that Jett 557 ms later. Separately, you trade Fade's death to Chamber after 4.079s under the default 5s definition."},
        {"id":"surviving_teammate_fight","round":3,"start_s":2.262,"end_s":2.429,
         "check":"Teammate Raze damages enemy Chamber; no Raze death in this observed damage group. The fight remains included without your damage contribution."},
        {"id":"nonlethal_contribution","round":20,"start_s":85.957,"end_s":87.793,
         "check":"Enemy Chamber damages teammate Raze; you deal 57.5 then about 11.61 actual damage to Chamber; Raze gets the kill with Paint Shells. Your roughly 69.11 damage remains a contribution without your kill."},
    ]
    for case in cases:
        case["verification_status"] = "pending_user_playback_check"
        case["replay_start_s"] = round(reports[case["round"]]["round"]["live_ms"]/1000+case["start_s"],3)
        case["replay_end_s"] = round(reports[case["round"]]["round"]["live_ms"]/1000+case["end_s"],3)
    manifest = {"match_id":model["match_id"],"revision":model["revision"],
                "status":"implementation_available; independent_playback_checks_pending", "cases":cases}
    lines = ["# First-query replay verification", "",
             "These reports are generated by the new query from Parquet. Automated regression checks do not replace your independent playback checks. "
             "Every checkbox below is still pending. Record corrections rather than marking a questionable observation as verified.", "",
             "Round times are seconds since barriers drop. Replay times are seconds since the replay begins; "
             "the in-game countdown uses a different display. Small replication delays are preserved in JSON as `observed_time_ms`.", "",
             f"Match `{model['match_id']}` · revision `{model['revision'][:16]}`.", ""]
    for case in cases:
        n=case["round"]
        lines += [f"- [ ] **{case['id'].replace('_',' ')}** — [round {n} report](round-{n:02}.md), "
                  f"round +{case['start_s']:.3f}s to +{case['end_s']:.3f}s "
                  f"(replay {case['replay_start_s']:.3f}s to {case['replay_end_s']:.3f}s). {case['check']}",
                  "  - Playback result/correction: pending."]
    lines += ["", "## Reading trade and participation evidence", "",
              "The default trade window is 5 seconds; exact delays are included so you can judge a different definition. "
              "Fight summaries use a 3-second inactivity gap and contextual response windows of 3 seconds before / 5 seconds after the exchange. "
              "They include all teammate damage exchanges while you are alive, without a distance cutoff. "
              "No recorded damage does not establish that you did not swing, fire, or help. Visibility and actual opportunity remain unknown.", "",
              "## Reports", ""]
    for n in reports:
        lines.append(f"- Round {n}: [readable timeline](round-{n:02}.md) · [JSON evidence](round-{n:02}.json)")
    output.mkdir(parents=True, exist_ok=False)
    for n, report in reports.items():
        (output/f"round-{n:02}.json").write_text(json.dumps(report,indent=2,ensure_ascii=False,allow_nan=False)+"\n",encoding="utf-8")
        (output/f"round-{n:02}.md").write_text(render_round(report),encoding="utf-8")
    (output/"verification.json").write_text(json.dumps(manifest,indent=2,ensure_ascii=False)+"\n",encoding="utf-8")
    (output/"verification.md").write_text("\n".join(lines)+"\n",encoding="utf-8")
    print(f"Created {output / 'verification.md'}; all independent playback checks remain pending.")


if __name__ == "__main__":
    main()
